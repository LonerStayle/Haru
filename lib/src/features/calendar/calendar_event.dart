/// 앱이 연동할 수 있는 캘린더 서비스 종류.
///
/// **왜 enum 인가** — 할 일 하나가 어느 서비스의 어느 이벤트에 묶였는지 구분해야
/// 하고(구글과 마이크로소프트를 동시에 켤 수 있다), 큐에 쌓인 작업도 어느 게이트웨이로
/// 보낼지 알아야 한다. 문자열을 그대로 들고 다니면 오타가 조용히 "구글" 로 흘러간다.
enum CalendarProvider {
  /// Google Calendar (`googleapis` calendar v3).
  google(wire: 'google', originTag: 'gcal', label: 'Google Calendar'),

  /// Microsoft 365 / Outlook 캘린더 (Microsoft Graph). Teams 회의 일정이 여기 쌓인다.
  microsoft(wire: 'microsoft', originTag: 'msgraph', label: 'Microsoft 365');

  const CalendarProvider({
    required this.wire,
    required this.originTag,
    required this.label,
  });

  /// DB / 설정 저장에 쓰는 값. **바꾸면 기존 데이터가 다른 provider 로 읽힌다.**
  final String wire;

  /// [Todo.calendarOrigin] 에 기록할 "이 서비스에서 유입됨" 표식.
  /// 구글은 과거 데이터와의 호환 때문에 `'gcal'` 을 유지한다.
  final String originTag;

  /// 사용자에게 보일 이름.
  final String label;

  /// 저장된 문자열 → provider. **모르는 값과 null 은 전부 구글**이다 —
  /// provider 필드가 생기기 전 데이터(전부 구글 연동)와의 하위호환이 여기서 성립한다.
  static CalendarProvider fromWire(String? wire) {
    for (final p in CalendarProvider.values) {
      if (p.wire == wire) return p;
    }
    return CalendarProvider.google;
  }

  /// [Todo.calendarOrigin] 값 → provider. 위와 같은 하위호환 규칙.
  static CalendarProvider fromOriginTag(String? tag) {
    for (final p in CalendarProvider.values) {
      if (p.originTag == tag) return p;
    }
    return CalendarProvider.google;
  }
}

/// 이벤트의 시각 한쪽(시작 또는 종료).
///
/// 종일 이벤트는 [date] 만, 시간이 정해진 이벤트는 [dateTime] 만 채운다. 두 서비스
/// 모두 이 이분법을 갖고 있다 (구글은 `start.date` vs `start.dateTime`, 그래프는
/// `isAllDay` 플래그 + `dateTimeTimeZone`).
class CalEventTime {
  const CalEventTime({this.date, this.dateTime});

  /// 종일 이벤트의 날짜(시각 없음).
  const CalEventTime.allDay(DateTime this.date) : dateTime = null;

  /// 시각이 정해진 이벤트의 시점.
  const CalEventTime.at(DateTime this.dateTime) : date = null;

  final DateTime? date;
  final DateTime? dateTime;

  bool get isAllDay => date != null;

  /// 날짜/시각 중 채워진 쪽. 둘 다 비어 있으면 null.
  DateTime? get value => date ?? dateTime;

  @override
  bool operator ==(Object other) =>
      other is CalEventTime && other.date == date && other.dateTime == dateTime;

  @override
  int get hashCode => Object.hash(date, dateTime);

  @override
  String toString() => date != null
      ? 'CalEventTime.allDay($date)'
      : 'CalEventTime.at($dateTime)';
}

/// 이벤트의 반복.
///
/// [rule] 이 null 이면 "반복이긴 한데 우리 모델로 표현할 수 없다" 는 뜻이다 —
/// 근사해서 조용히 어긋나느니 단일 할 일로 폴백하고 그 사실을 남긴다.
class CalRecurrence {
  const CalRecurrence({this.rule, this.until});

  final RecurrenceRule? rule;
  final DateTime? until;

  /// 우리 모델로 표현 가능한 반복인가.
  bool get isSupported => rule != null;

  @override
  bool operator ==(Object other) =>
      other is CalRecurrence && other.rule == rule && other.until == until;

  @override
  int get hashCode => Object.hash(rule, until);

  @override
  String toString() => 'CalRecurrence($rule, until: $until)';
}

/// **provider 중립 이벤트 DTO.**
///
/// 동기화 로직(큐 flush · 증분 수신 · echo 차단 · LWW 병합 · 삭제 규칙)은 전부 이
/// 타입만 안다. `googleapis` 의 `gcal.Event` 나 Microsoft Graph 의 JSON 은 각
/// 게이트웨이 구현체 안에서만 존재한다.
///
/// **왜 이 타입이 필요한가** — 예전에는 [CalendarGateway] 가 `gcal.Event` 를 직접
/// 주고받아서, 두 번째 서비스(Microsoft)를 붙이려면 병합·필터·매핑을 전부 복제해야
/// 했다. 지금은 게이트웨이가 자기 형식으로 번역만 하면 나머지가 그대로 재사용된다.
class CalEvent {
  const CalEvent({
    this.id,
    this.title,
    this.description,
    this.start,
    this.end,
    this.cancelled = false,
    this.updated,
    this.recurrence,
    this.appProperties = const {},
    this.markDone = false,
    this.autoGenerated = false,
    this.organizerIsSelf,
    this.selfResponseStatus,
  });

  /// 서비스가 부여한 이벤트 id. 생성 요청에는 없다.
  final String? id;

  /// 제목 (구글 `summary` / 그래프 `subject`).
  final String? title;

  final String? description;

  final CalEventTime? start;

  /// 종료 시각. 종일 이벤트의 종료는 **exclusive(종료 다음날)** 로 담는다 —
  /// 두 서비스 모두 같은 규칙이라 DTO 도 그 규칙을 그대로 쓴다.
  final CalEventTime? end;

  /// 취소(삭제)된 이벤트인가. 증분 수신에서 tombstone 으로 도착한다.
  final bool cancelled;

  /// 서버가 기록한 마지막 수정 시각. last-write-wins 비교의 한쪽 항이다.
  final DateTime? updated;

  final CalRecurrence? recurrence;

  /// 앱이 이벤트에 심어두는 서명 (`haruTodoId` / `haruRev` / ...).
  ///
  /// 구글은 `extendedProperties.private`, 그래프는 `singleValueExtendedProperties`
  /// 로 실어 나른다. 서비스가 되돌려주지 못하면 빈 맵이며, 그때도 동기화가 깨지지
  /// 않도록 병합 쪽에 "내용이 같으면 echo" 규칙이 따로 있다.
  final Map<String, String> appProperties;

  /// 완료 표시. 구글은 회색(colorId 8)으로 반영하고, Outlook 은 이벤트 단위 색
  /// 지정이 마스터 범주 등록을 요구해 이번 범위에서는 반영하지 않는다.
  final bool markDone;

  /// 생일·공휴일·자동 생성 등 할 일로서 의미가 없는 이벤트인가.
  final bool autoGenerated;

  /// 내가 주최자인가. **모르면 null** — null 을 "남의 일정" 으로 취급하면 개인
  /// 캘린더의 단독 일정이 하나도 안 들어온다.
  final bool? organizerIsSelf;

  /// 초대에 대한 내 응답 (`'declined'` 등). 모르면 null.
  final String? selfResponseStatus;

  CalEvent copyWith({
    String? id,
    String? title,
    String? description,
    CalEventTime? start,
    CalEventTime? end,
    bool? cancelled,
    DateTime? updated,
    CalRecurrence? recurrence,
    Map<String, String>? appProperties,
    bool? markDone,
    bool? autoGenerated,
    bool? organizerIsSelf,
    String? selfResponseStatus,
  }) {
    return CalEvent(
      id: id ?? this.id,
      title: title ?? this.title,
      description: description ?? this.description,
      start: start ?? this.start,
      end: end ?? this.end,
      cancelled: cancelled ?? this.cancelled,
      updated: updated ?? this.updated,
      recurrence: recurrence ?? this.recurrence,
      appProperties: appProperties ?? this.appProperties,
      markDone: markDone ?? this.markDone,
      autoGenerated: autoGenerated ?? this.autoGenerated,
      organizerIsSelf: organizerIsSelf ?? this.organizerIsSelf,
      selfResponseStatus: selfResponseStatus ?? this.selfResponseStatus,
    );
  }

  @override
  String toString() =>
      'CalEvent($id, "$title", $start~$end, cancelled: $cancelled)';
}
