import 'package:flutter_test/flutter_test.dart';
import 'package:googleapis/calendar/v3.dart' as gcal;

import 'package:solo_todo/src/domain/recurrence.dart';
import 'package:solo_todo/src/features/calendar/calendar_event.dart';
import 'package:solo_todo/src/features/calendar/google_calendar_gateway.dart';

/// provider 중립 [CalEvent] ↔ `googleapis` 이벤트 변환.
///
/// 이 변환이 구글 연동의 **유일한** 접점이 됐다. 여기가 어긋나면 기존 동기화가
/// 통째로 조용히 틀어지므로, 왕복과 각 필드의 대응을 하나씩 고정한다.
void main() {
  group('CalEvent → gcal.Event', () {
    test('종일은 date, 시간은 dateTime(UTC) 으로 나간다', () {
      final allDay = toGoogleEvent(
        CalEvent(
          title: '휴가',
          start: CalEventTime.allDay(DateTime(2026, 8, 20)),
          end: CalEventTime.allDay(DateTime(2026, 8, 23)),
        ),
      );
      expect(allDay.start!.date, DateTime(2026, 8, 20));
      expect(allDay.start!.dateTime, isNull);
      expect(allDay.end!.date, DateTime(2026, 8, 23));

      final timed = toGoogleEvent(
        CalEvent(
          title: '회의',
          start: CalEventTime.at(DateTime.utc(2026, 8, 20, 14)),
          end: CalEventTime.at(DateTime.utc(2026, 8, 20, 15)),
        ),
      );
      expect(timed.start!.date, isNull);
      expect(timed.start!.dateTime, DateTime.utc(2026, 8, 20, 14));
      expect(timed.start!.timeZone, 'UTC');
    });

    test('완료 표시는 회색(colorId 8), 미완료는 null 로 기본색 복구', () {
      final done = toGoogleEvent(
        CalEvent(
          title: 'x',
          markDone: true,
          start: CalEventTime.at(DateTime.utc(2026, 8, 20, 14)),
        ),
      );
      expect(done.colorId, '8');

      final undone = toGoogleEvent(
        CalEvent(
          title: 'x',
          start: CalEventTime.at(DateTime.utc(2026, 8, 20, 14)),
        ),
      );
      expect(undone.colorId, isNull);
    });

    test('앱 서명은 extendedProperties.private 로 실린다', () {
      final e = toGoogleEvent(
        const CalEvent(title: 'x', appProperties: {'haruTodoId': 'todo-1'}),
      );
      expect(e.extendedProperties!.private, {'haruTodoId': 'todo-1'});
    });

    test('서명이 비어 있으면 extendedProperties 를 붙이지 않는다', () {
      expect(
        toGoogleEvent(const CalEvent(title: 'x')).extendedProperties,
        isNull,
      );
    });

    test('반복은 RRULE 문자열 1개로 나간다 (UNTIL 포함)', () {
      final e = toGoogleEvent(
        CalEvent(
          title: 'x',
          start: CalEventTime.at(DateTime.utc(2026, 8, 20, 14)),
          recurrence: CalRecurrence(
            rule: const RecurrenceRule(
              freq: RecurrenceFreq.weekly,
              byWeekday: {1},
            ),
            until: DateTime.utc(2026, 12, 31),
          ),
        ),
      );
      expect(e.recurrence, [
        'RRULE:FREQ=WEEKLY;INTERVAL=1;BYDAY=MO;UNTIL=20261231T000000Z',
      ]);
    });

    test('표현 불가 반복(rule 없음)은 RRULE 을 만들지 않는다', () {
      final e = toGoogleEvent(
        CalEvent(
          title: 'x',
          start: CalEventTime.at(DateTime.utc(2026, 8, 20, 14)),
          recurrence: const CalRecurrence(),
        ),
      );
      expect(e.recurrence, isNull);
    });
  });

  group('gcal.Event → CalEvent', () {
    test('취소 상태 · 수정 시각 · 제목이 그대로 넘어온다', () {
      final e = fromGoogleEvent(
        gcal.Event(
          id: 'ev-1',
          summary: '회의',
          status: 'cancelled',
          updated: DateTime.utc(2026, 8, 19, 8),
        ),
      );
      expect(e.id, 'ev-1');
      expect(e.title, '회의');
      expect(e.cancelled, isTrue);
      expect(e.updated, DateTime.utc(2026, 8, 19, 8));
    });

    test('자동 생성 이벤트 종류가 플래그로 접힌다', () {
      for (final type in ['birthday', 'fromGmail', 'workingLocation']) {
        expect(
          fromGoogleEvent(gcal.Event(id: 'x', eventType: type)).autoGenerated,
          isTrue,
          reason: type,
        );
      }
      expect(
        fromGoogleEvent(
          gcal.Event(id: 'x', eventType: 'default'),
        ).autoGenerated,
        isFalse,
      );
    });

    test('주최자 정보가 없으면 null 을 유지한다', () {
      expect(fromGoogleEvent(gcal.Event(id: 'x')).organizerIsSelf, isNull);
      expect(
        fromGoogleEvent(
          gcal.Event(id: 'x', organizer: gcal.EventOrganizer(self: false)),
        ).organizerIsSelf,
        isFalse,
      );
    });

    test('내 응답 상태는 attendees 중 self 에서 읽는다', () {
      final e = fromGoogleEvent(
        gcal.Event(
          id: 'x',
          attendees: [
            gcal.EventAttendee(email: 'other@example.com'),
            gcal.EventAttendee(self: true, responseStatus: 'declined'),
          ],
        ),
      );
      expect(e.selfResponseStatus, 'declined');
    });

    test('표현 가능한 RRULE 은 규칙으로, 아니면 "반복이지만 표현 불가" 로', () {
      final ok = fromGoogleEvent(
        gcal.Event(id: 'x', recurrence: ['RRULE:FREQ=DAILY;INTERVAL=3']),
      );
      expect(
        ok.recurrence!.rule,
        const RecurrenceRule(freq: RecurrenceFreq.daily, interval: 3),
      );

      final unsupported = fromGoogleEvent(
        gcal.Event(
          id: 'x',
          recurrence: ['RRULE:FREQ=MONTHLY;BYDAY=MO;BYSETPOS=1'],
        ),
      );
      expect(unsupported.recurrence, isNotNull);
      expect(unsupported.recurrence!.isSupported, isFalse);

      expect(fromGoogleEvent(gcal.Event(id: 'x')).recurrence, isNull);
    });

    test('EXDATE 만 있고 RRULE 이 없으면 반복이 아니다', () {
      expect(
        fromGoogleEvent(
          gcal.Event(id: 'x', recurrence: ['EXDATE;VALUE=DATE:20260821']),
        ).recurrence,
        isNull,
      );
    });
  });

  group('왕복', () {
    test('시간 이벤트가 값 손실 없이 돌아온다', () {
      final original = CalEvent(
        title: '회의',
        description: '설명',
        start: CalEventTime.at(DateTime.utc(2026, 8, 20, 14)),
        end: CalEventTime.at(DateTime.utc(2026, 8, 20, 15)),
        markDone: true,
        appProperties: const {'haruTodoId': 'todo-1', 'haruRev': 'rev'},
      );
      final back = fromGoogleEvent(toGoogleEvent(original));
      expect(back.title, original.title);
      expect(back.description, original.description);
      expect(back.start, original.start);
      expect(back.end, original.end);
      expect(back.markDone, isTrue);
      expect(back.appProperties, original.appProperties);
    });

    test('종일 이벤트가 값 손실 없이 돌아온다', () {
      final original = CalEvent(
        title: '휴가',
        start: CalEventTime.allDay(DateTime(2026, 8, 20)),
        end: CalEventTime.allDay(DateTime(2026, 8, 23)),
      );
      final back = fromGoogleEvent(toGoogleEvent(original));
      expect(back.start!.date, DateTime(2026, 8, 20));
      expect(back.end!.date, DateTime(2026, 8, 23));
      expect(back.start!.dateTime, isNull);
    });
  });
}
